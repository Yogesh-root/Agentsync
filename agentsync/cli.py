"""agentsync: one source of truth for every AI coding agent's instructions."""
import argparse, hashlib, re, shutil, sys
from pathlib import Path
from . import __version__

MARK = "agentsync:generated"
HASHFILE = ".agentsync-hash"
SRC = "AGENTS.md"
SKILLS_SRC, SKILLS_DST = ".agents/skills", ".claude/skills"
TARGETS = {
    "claude": "CLAUDE.md",
    "gemini": "GEMINI.md",
    "copilot": ".github/copilot-instructions.md",
    "windsurf": ".windsurfrules",
    "cursor": ".cursor/rules/agents.mdc",
}
SECRETS = [
    (r"sk-[A-Za-z0-9_-]{20,}", "API key (sk-...)"),
    (r"AKIA[0-9A-Z]{16}", "AWS access key"),
    (r"ghp_[A-Za-z0-9]{30,}", "GitHub token"),
    (r"-----BEGIN [A-Z ]*PRIVATE KEY-----", "private key"),
]
TEMPLATE = """# Project instructions

## Commands
- Build: `make build`
- Test: `make test`

## Conventions
- Keep changes small and focused.
- Write tests for new behaviour.

## Never
- Commit secrets or edit generated files by hand.
"""
SKILL_TEMPLATE = """---
name: example
description: Use when the user asks for an example skill. Replace me.
---
# Example skill
Steps the agent should follow go here.
"""

tty = sys.stdout.isatty()
def c(code, s): return f"\033[{code}m{s}\033[0m" if tty else s
OK, WARN, BAD = (lambda s: c(32, s)), (lambda s: c(33, s)), (lambda s: c(31, s))

def digest(text): return hashlib.sha256(text.encode()).hexdigest()[:12]

def render(name, body):
    header = f"<!-- {MARK} sha256={digest(body)} | source: {SRC} | edit the source, then run `agentsync sync` -->"
    front = "---\ndescription: Project rules synced from AGENTS.md\nalwaysApply: true\n---\n" if name == "cursor" else ""
    return f"{front}{header}\n\n{body}"

def file_state(path, expected):
    if not path.exists(): return "missing"
    text = path.read_text(encoding="utf-8", errors="replace")
    if text == expected: return "ok"
    return "stale" if MARK in text else "foreign"

def tree_hash(d):
    h = hashlib.sha256()
    for f in sorted(p for p in d.rglob("*") if p.is_file() and p.name != HASHFILE):
        h.update(str(f.relative_to(d)).encode()); h.update(f.read_bytes())
    return h.hexdigest()[:12]

def skill_dirs(root):
    base = root / SKILLS_SRC
    return sorted(d for d in base.iterdir() if (d / "SKILL.md").is_file()) if base.is_dir() else []

def skill_state(src, dst):
    if not dst.exists(): return "missing"
    hf = dst / HASHFILE
    if not hf.exists(): return "foreign"
    return "ok" if hf.read_text().strip() == tree_hash(src) == tree_hash(dst) else "stale"

def plan(root, only):
    """Yield (kind, label, state, apply_fn)."""
    body = (root / SRC).read_text(encoding="utf-8")
    for name, rel in TARGETS.items():
        if only and name not in only: continue
        p, exp = root / rel, render(name, body)
        def apply(p=p, exp=exp):
            p.parent.mkdir(parents=True, exist_ok=True); p.write_text(exp, encoding="utf-8")
        yield "rules", rel, file_state(p, exp), apply
    if not only or "claude" in only:
        for s in skill_dirs(root):
            dst = root / SKILLS_DST / s.name
            def apply(s=s, dst=dst):
                if dst.exists(): shutil.rmtree(dst)
                shutil.copytree(s, dst); (dst / HASHFILE).write_text(tree_hash(s))
            yield "skill", f"{SKILLS_DST}/{s.name}", skill_state(s, dst), apply

def cmd_sync(a):
    root = Path(a.root)
    if not (root / SRC).exists():
        print(BAD(f"No {SRC} found. Run `agentsync init` first.")); return 2
    only = set(a.only.split(",")) if a.only else None
    drift = 0
    for kind, label, state, apply in plan(root, only):
        if state == "ok": print(f"  {OK('ok     ')} {label}"); continue
        if state == "foreign" and not a.force:
            print(f"  {WARN('skipped')} {label} (exists, not generated by agentsync; use --force)"); drift += 1; continue
        drift += 1
        if a.check or a.dry_run: print(f"  {BAD(state.ljust(7))} {label}"); continue
        apply(); print(f"  {OK('wrote  ')} {label}")
    if a.check and drift: print(BAD(f"{drift} file(s) out of sync")); return 1
    return 0

def cmd_init(a):
    root = Path(a.root); src = root / SRC
    if src.exists(): print(WARN(f"{SRC} already exists, leaving it alone."))
    else:
        adopted = next((root / t for t in ("CLAUDE.md", "GEMINI.md", ".github/copilot-instructions.md") if (root / t).exists()), None)
        if adopted:
            txt = re.sub(r"<!-- agentsync:generated.*?-->\n*", "", adopted.read_text(encoding="utf-8"))
            src.write_text(txt, encoding="utf-8"); print(OK(f"Adopted {adopted.relative_to(root)} as {SRC}"))
        else:
            src.write_text(TEMPLATE, encoding="utf-8"); print(OK(f"Created {SRC}"))
    ex = root / SKILLS_SRC / "example" / "SKILL.md"
    if not (root / SKILLS_SRC).exists():
        ex.parent.mkdir(parents=True); ex.write_text(SKILL_TEMPLATE); print(OK(f"Created {SKILLS_SRC}/example"))
    print("Next: `agentsync sync` (add --force once to take over existing agent files).")
    return 0

def cmd_doctor(a):
    root = Path(a.root); problems = 0
    def report(level, msg):
        nonlocal problems
        problems += level == "bad"; print(f"  {OK('pass') if level=='ok' else WARN('warn') if level=='warn' else BAD('FAIL')}  {msg}")
    src = root / SRC
    if not src.exists(): report("bad", f"{SRC} missing"); return 1
    text = src.read_text(encoding="utf-8"); toks = len(text) // 4
    report("ok" if toks <= 2000 else "warn", f"{SRC} is ~{toks} tokens" + ("" if toks <= 2000 else " (long instructions get ignored; aim for <2000)"))
    hits = [lbl for rx, lbl in SECRETS if re.search(rx, text)]
    report("bad" if hits else "ok", f"secrets in {SRC}: {', '.join(hits)}" if hits else "no secrets detected")
    for s in skill_dirs(root):
        t = (s / "SKILL.md").read_text(encoding="utf-8")
        fm = re.match(r"---\n(.*?)\n---", t, re.S)
        ok = fm and re.search(r"^name:\s*\S", fm.group(1), re.M) and re.search(r"^description:\s*\S", fm.group(1), re.M)
        report("ok" if ok else "bad", f"skill {s.name}: " + ("valid frontmatter" if ok else "needs `name` and `description` frontmatter"))
    drift = [l for _, l, st, _ in plan(root, None) if st != "ok"]
    report("warn" if drift else "ok", f"{len(drift)} target(s) out of sync: {', '.join(drift)}" if drift else "all targets in sync")
    return 1 if problems else 0

def main(argv=None):
    p = argparse.ArgumentParser(prog="agentsync", description=__doc__)
    p.add_argument("--version", action="version", version=__version__)
    p.add_argument("--root", default=".", help="project root")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init", help="create or adopt AGENTS.md").set_defaults(fn=cmd_init)
    s = sub.add_parser("sync", help="generate every agent's files from AGENTS.md")
    s.add_argument("--check", action="store_true", help="exit 1 on drift (for CI)")
    s.add_argument("--dry-run", action="store_true"); s.add_argument("--force", action="store_true")
    s.add_argument("--only", help="comma list: " + ",".join(TARGETS)); s.set_defaults(fn=cmd_sync)
    sub.add_parser("doctor", help="lint instructions, skills, secrets, drift").set_defaults(fn=cmd_doctor)
    a = p.parse_args(argv)
    return a.fn(a)
